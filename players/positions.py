# L/R остаются собой, C/LC/RC схлопываются в "C" — см. докстринг выше про
# причину (CB1/CB2 взаимозаменяемы, отдельных "левый ЦЗ"/"правый ЦЗ" нет).
_FIELD_POSITION_ZONE: dict[str, str] = {
    "L": "L",
    "R": "R",
    "C": "C",
    "LC": "C",
    "RC": "C",
}


def resolve_lineup_codes(amplua: str | None, field_position: str | None) -> list[str]:
    """Код(ы) для регистрации кандидата в pool_by_code (season_squad и
    round_squad services.py) — см. докстринг SLOT_PROCESSING_ORDER выше.

    :return: список из ОДНОГО кода — либо комбинированного "AMPLUA:ZONE",
      если сторона известна, либо голого "AMPLUA" для старых записей без
      field_position. Пустой список, если амплуа вообще не распознано."""
    amplua_code = clean_position_code(amplua)
    if not amplua_code:
        return []
    zone = _FIELD_POSITION_ZONE.get(clean_position_code(field_position), "")
    if zone:
        return [f"{amplua_code}:{zone}"]
    return [amplua_code]

