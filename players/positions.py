# "Живая сборная сезона" (season_squad) и "DOPX Лучшие тура" (round_squad) —
# маппинг слотов формации 4-3-3 на пулы допустимых кодов позиций.
#
# Слот определяется комбинацией amplua+field_position, с фолбэком на голый
# код amplua для старых записей без field_position. См.
# docs/adr/0010-lineup-slot-side-resolution.md.
#
# ИСПРАВЛЕНО (2026-09-21, жалоба пользователя: "некоторые игроки стоят
# например на правом полузащитнике, а сам игрок например не играет там
# вообще"). КОРНЕВАЯ ПРИЧИНА — у СТОРОННИХ (боковых) слотов RB/LB/RW/LW
# фолбэк раньше доходил до ГОЛЫХ, лишённых стороны кодов ("D"/"DF" для
# защиты, "AM"/"F" для атаки) — тот же самый голый код "AM", например,
# стоял одновременно и в списке RW, и в списке LW. Если ни у кого не
# набиралось РЕАЛЬНО стороннего кода (M:R/AM:R и т.п.) на этот слот, жадный
# алгоритм добирался до голого пула и брал лучшего по рейтингу игрока
# оттуда — совершенно не глядя, играл ли он вообще когда-либо именно на
# этом фланге. Голый код появляется не только из старых записей без
# field_position (для чего фолбэк изначально задумывался), но и из
# КАЖДОГО невышедшего запасного (field_position не считается для тех, кто
# не выходил на поле, см. _player_season_position/_build_round_player_data)
# — то есть игрок, просидевший весь сезон на скамейке под "AM", мог
# оказаться "правым вингером сезона" просто по счастливому амплуа в заявке.
#
# Фикс: для СТОРОННИХ слотов (RB/LB/RW/LW) голые коды без стороны убраны
# из фолбэка целиком — если ни один кандидат не подтверждён стороной, слот
# лучше оставить пустым ("недостаточно данных"), чем угадать не ту
# сторону. Для НЕ-сторонних слотов (CB1/CB2, DM/CM1/CM2, ST) голый фолбэк
# сохранён как был — там сторона в принципе не имеет значения (см.
# докстринг ниже про CB1/CB2), угадывать нечего.
#
# ИСПРАВЛЕНО (2026-09-22, автотест test_bare_code_player_does_not_win_side_
# slot_over_specific_winger упал на реальном прогоне пользователя): даже
# после фикса выше слот RW у игрока с чётким "M:R" всё равно оставался
# ПУСТЫМ. КОРНЕВАЯ ПРИЧИНА — ПОРЯДОК обработки слотов, не пул кодов. CM2
# тоже принимает код "M:R" (как слабый тай-брейк между CM1/CM2, когда не
# хватает однозначно центральных кандидатов), а CM2 в списке ШЁЛ РАНЬШЕ
# RW — жадный алгоритм успевал забрать единственного кандидата с "M:R" в
# CM2, и когда очередь доходила до RW, пул под этим кодом был уже пуст.
# Тот же конфликт — у CM1 с LW через код "M:L". Правильный приоритет:
# специфичный сторонний слот (RW/LW) — куда игрок с M:R/M:L подходит по
# СМЫСЛУ кода напрямую (см. сам список кодов RW/LW, где M:R/M:L стоят
# вторыми по силе после AM:R/AM:L) — должен забирать такого кандидата
# РАНЬШЕ, чем CM1/CM2 успеет использовать его как второсортный тай-брейк.
# Поэтому RW/LW переставлены выше CM1/CM2 в порядке обработки.
SLOT_PROCESSING_ORDER: list[tuple[str, list[str]]] = [
    ("GK", ["GK:C", "GK"]),
    ("CB1", ["D:C", "CB", "DF", "D"]),
    ("CB2", ["D:C", "CB", "DF", "D"]),
    ("RB", ["D:R", "RB", "RWB"]),
    ("LB", ["D:L", "LB", "LWB"]),
    ("RW", ["AM:R", "M:R", "F:R", "RW", "W", "RM"]),
    ("LW", ["AM:L", "M:L", "F:L", "LW", "W", "LM"]),
    ("DM", ["DM:C", "DM", "CM", "M", "MF"]),
    ("CM1", ["DM:L", "M:C", "M:L", "AM:C", "CM", "M", "MF"]),
    ("CM2", ["DM:R", "M:C", "M:R", "AM:C", "CM", "M", "MF"]),
    ("ST", ["F:C", "ST", "CF", "F", "FW"]),
]

# L/R остаются собой, C/LC/RC схлопываются в "C" — см. докстринг выше про
# причину (CB1/CB2 взаимозаменяемы, отдельных "левый ЦЗ"/"правый ЦЗ" нет).
_FIELD_POSITION_ZONE: dict[str, str] = {
    "L": "L",
    "R": "R",
    "C": "C",
    "LC": "C",
    "RC": "C",
}


def resolve_lineup_codes(amplua: str | None, field_position: str | None) -> list[str]:
    """Код(ы) для регистрации кандидата в pool_by_code (season_squad и
    round_squad services.py) — см. докстринг SLOT_PROCESSING_ORDER выше.

    :return: список из ОДНОГО кода — либо комбинированного "AMPLUA:ZONE",
      если сторона известна, либо голого "AMPLUA" для старых записей без
      field_position. Пустой список, если амплуа вообще не распознано."""
    amplua_code = clean_position_code(amplua)
    if not amplua_code:
        return []
    zone = _FIELD_POSITION_ZONE.get(clean_position_code(field_position), "")
    if zone:
        return [f"{amplua_code}:{zone}"]
    return [amplua_code]

