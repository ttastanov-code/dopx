# Обратная карта label -> [коды] — нужна для фильтра в players/views.py:
# в выпадающем списке должны быть УНИКАЛЬНЫЕ подписи (иначе "AM"/"CAM"/
# "SS", если такие водятся в сырых данных KFF, дали бы несколько
# одинаковых на вид пунктов "Атакующий полузащитник" подряд), а выбор
# одной подписи должен фильтровать ПО ВСЕМ кодам, которые в неё
# схлопнулись.
LABEL_TO_CODES: dict[str, list[str]] = {}
for _code, _label in POSITION_LABELS.items():
    LABEL_TO_CODES.setdefault(_label, []).append(_code)


def clean_position_code(raw: str | None) -> str:
    """Только нормализация регистра/пробелов — используется при записи в
    БД (импорт KFF, миграция бэкафилла). НЕ отбрасывает нераспознанные
    коды — сохраняет данные как есть, просто в едином регистре."""
    if not raw:
        return ""
    return raw.strip().upper()


def position_label(code: str | None) -> str | None:
    """Человекочитаемая подпись для отображения. None для нераспознанного
    кода — шаблоны должны показывать "—", а не сырую аббревиатуру."""
    if not code:
        return None
    return POSITION_LABELS.get(code.strip().upper())


