# players/positions.py
"""
Нормализация позиций игроков. Источник сырых данных — KFF API, поле
`amplua`/`position` в ответе на состав (parsers/kff/importers.py) —
приходит произвольным регистром и без единого словаря значений (видели на
практике: "DM", "M", "F", "GK", "Gk" вперемешку для одного и того же
амплуа). Модель Player.position и MatchLineupPlayer.position — свободный
CharField БЕЗ choices намеренно: неизвестный код лучше сохранить как есть
(на случай будущего маппинга), чем потерять данные или уронить импорт.

Разделение по двум функциям — намеренное:
- clean_position_code(): вызывается при ЗАПИСИ (импорт из KFF, миграция
  бэкафилла) — только normalizует регистр/пробелы, НЕ теряет данные, даже
  если код не входит в POSITION_LABELS (парсер может завтра прислать новый
  валидный код, которого ещё нет в словаре — не должны его портить).
- position_label(): вызывается при ОТОБРАЖЕНИИ (шаблоны) — возвращает
  None для нераспознанных кодов, чтобы шаблон показал "—", а не
  сырую аббревиатуру, вводящую пользователя в заблуждение.
"""
from __future__ import annotations

# Ключи — канонический код ПОСЛЕ clean_position_code() (upper + strip).
# Покрывает стандартные англоязычные аббревиатуры позиций плюс варианты,
# реально встречавшиеся в данных KFF на практике.
POSITION_LABELS: dict[str, str] = {
    "GK": "Вратарь",
    "DF": "Защитник",
    "CB": "Центральный защитник",
    "LB": "Левый защитник",
    "RB": "Правый защитник",
    "LWB": "Левый латераль",
    "RWB": "Правый латераль",
    "DM": "Опорный полузащитник",
    "CM": "Центральный полузащитник",
    "M": "Полузащитник",
    "MF": "Полузащитник",
    "AM": "Атакующий полузащитник",
    "LM": "Левый полузащитник",
    "RM": "Правый полузащитник",
    "WM": "Крайний полузащитник",
    "F": "Нападающий",
    "FW": "Нападающий",
    "ST": "Нападающий",
    "CF": "Центральный нападающий",
    "W": "Вингер",
    "LW": "Левый вингер",
    "RW": "Правый вингер",
}


# Обратная карта label -> [коды] — нужна для фильтра в players/views.py:
# в выпадающем списке должны быть УНИКАЛЬНЫЕ подписи (иначе "AM"/"CAM"/
# "SS", если такие водятся в сырых данных KFF, дали бы несколько
# одинаковых на вид пунктов "Атакующий полузащитник" подряд), а выбор
# одной подписи должен фильтровать ПО ВСЕМ кодам, которые в неё
# схлопнулись.
LABEL_TO_CODES: dict[str, list[str]] = {}
for _code, _label in POSITION_LABELS.items():
    LABEL_TO_CODES.setdefault(_label, []).append(_code)


def clean_position_code(raw: str | None) -> str:
    """Только нормализация регистра/пробелов — используется при записи в
    БД (импорт KFF, миграция бэкафилла). НЕ отбрасывает нераспознанные
    коды — сохраняет данные как есть, просто в едином регистре."""
    if not raw:
        return ""
    return raw.strip().upper()


def position_label(code: str | None) -> str | None:
    """Человекочитаемая подпись для отображения. None для нераспознанного
    кода — шаблоны должны показывать "—", а не сырую аббревиатуру."""
    if not code:
        return None
    return POSITION_LABELS.get(code.strip().upper())
