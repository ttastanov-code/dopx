# "Живая сборная сезона" (season_squad) — маппинг слотов формации 4-3-3 на
# пулы допустимых сырых кодов позиций (см. season_squad/services.py).
#
# SLOT_PROCESSING_ORDER — порядок ВАЖЕН: это не порядок отображения на поле
# (за него отвечает `order` в SeasonBestXISlot), а порядок ЗАПОЛНЕНИЯ слотов
# при подборе состава. Алгоритм жадный: после того как игрок занял слот, он
# исключается из пулов ВСЕХ остальных слотов этого пересчёта (один игрок не
# может быть одновременно, скажем, RB и CB2). Пулы соседних амплуа
# намеренно пересекаются (например CB1/CB2/RB/LB все допускают общий код
# "DF"/"D", если KFF прислал только общее "защитник" без уточнения фланга) —
# поэтому специфичные позиции (CB) обрабатываются РАНЬШЕ широких фолбэков
# (RB/LB, которые тоже принимают "DF"/"D"), чтобы игрок с точным кодом сначала
# получал самый подходящий слот, а не терялся в общем пуле.
#
# ВАЖНО про RW/LW (проверено на живой БД 2026-08-22, см. также запись про
# "D" выше): реальный набор сырых кодов, которые вообще присылает KFF —
# всего 6 штук: GK, D, DM, M, AM, F. Кодов "RW"/"LW"/"W"/"RM"/"LM" в данных
# НЕТ НИ РАЗУ — KFF не различает фланги у атакующих игроков вообще, поэтому
# слоты вингеров пустовали не из-за бага фильтрации, а потому что искали
# коды, которых физически не существует. "AM" (атакующий полузащитник) при
# этом раньше вообще нигде не встречался ни в одном пуле — терялся
# полностью. Фолбэк ниже — прагматичное решение под ограничение данных:
# отдаём вингерам "AM" (ближайшее по смыслу амплуа к атакующему флангу) и
# "F" (что осталось от нападающих после того, как ST уже забрал лучшего) —
# лучше приблизительно верный кандидат на фланге, чем гарантированно пустой
# слот. Если KFF когда-нибудь начнёт присылать честные W/RW/LW/RM/LM — они
# уже в пуле первыми, специфичные коды всегда в приоритете перед фолбэком.
