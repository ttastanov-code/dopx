    ("GK", ["GK:C", "GK"]),
    ("CB1", ["D:C", "CB", "DF", "D"]),
    ("CB2", ["D:C", "CB", "DF", "D"]),
    ("RB", ["D:R", "RB", "RWB", "DF", "D"]),
    ("LB", ["D:L", "LB", "LWB", "DF", "D"]),
    ("DM", ["DM:C", "DM", "CM", "M", "MF"]),
    ("CM1", ["DM:L", "M:C", "M:L", "AM:C", "CM", "M", "MF"]),
