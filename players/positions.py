# "Живая сборная сезона" (season_squad) и "DOPX Лучшие тура" (round_squad) —
# маппинг слотов формации 4-3-3 на пулы допустимых кодов позиций.
#
# ИСТОРИЯ (2026-08-22 → 2026-08-23): реальный набор сырых кодов, которые
# присылает KFF в поле `amplua`/`position` — всего 6 штук: GK, D, DM, M, AM,
# F, без разделения по флангу. Из-за этого CB1/CB2/RB/LB делили один и тот
# же пул "D" (сторону невозможно было определить), а вингеры RW/LW стояли
# на приблизительном фолбэке AM/F. 2026-08-23 обнаружилось, что в том же
# ответе `/games/<id>/lineup` у КАЖДОГО игрока есть ЕЩЁ ОДНО поле —
# `field_position` (`C`/`L`/`R`/`LC`/`RC` — колонка формации), которое
# просто не импортировалось (см. parsers/kff/importers.py и
# lineups/models.py::MatchLineupPlayer.field_position). Комбинация
# amplua+field_position и даёт точный слот без всяких фолбэков-угадаек.
#
# _resolve_lineup_codes() ниже сворачивает field_position в 3 зоны (L/C/R —
# LC и RC обе схлопываются в "C", т.к. у нас в формации CB1/CB2 всё равно
# взаимозаменяемы, отдельного слота "левый ЦЗ" не существует) и возвращает
# КОМБИНИРОВАННЫЙ код вида "D:L" — но ТОЛЬКО если field_position реально
# известен. Если это старая запись (синк до 2026-08-23, field_position
# пустой) — возвращается голый код "D", как раньше, БЕЗ комбинирования.
# Это принципиально: старые данные регистрируются ТОЛЬКО под голым кодом
# (общий пул на все 4 защитных слота, как было всегда), а новые — ТОЛЬКО
# под точным комбинированным (не дублируются в голый пул, иначе левый
# защитник с известной стороной снова попадал бы в конкуренты на ЦЗ).
# Голые коды остаются в списках ниже как приёмник именно для такой старой
# записи — не для новых, где сторона уже известна.
SLOT_PROCESSING_ORDER: list[tuple[str, list[str]]] = [
    ("GK", ["GK:C", "GK"]),
    ("CB1", ["D:C", "CB", "DF", "D"]),
    ("CB2", ["D:C", "CB", "DF", "D"]),
    ("RB", ["D:R", "RB", "RWB", "DF", "D"]),
    ("LB", ["D:L", "LB", "LWB", "DF", "D"]),
    ("DM", ["DM:C", "DM", "CM", "M", "MF"]),
    ("CM1", ["DM:L", "M:C", "M:L", "AM:C", "CM", "M", "MF"]),
    ("CM2", ["DM:R", "M:C", "M:R", "AM:C", "CM", "M", "MF"]),
    ("ST", ["F:C", "ST", "CF", "F", "FW"]),
    ("RW", ["AM:R", "M:R", "F:R", "RW", "W", "RM", "AM", "F"]),
    ("LW", ["AM:L", "M:L", "F:L", "LW", "W", "LM", "AM", "F"]),
]

# L/R остаются собой, C/LC/RC схлопываются в "C" — см. докстринг выше про
# причину (CB1/CB2 взаимозаменяемы, отдельных "левый ЦЗ"/"правый ЦЗ" нет).
_FIELD_POSITION_ZONE: dict[str, str] = {
    "L": "L",
    "R": "R",
    "C": "C",
    "LC": "C",
    "RC": "C",
}


def resolve_lineup_codes(amplua: str | None, field_position: str | None) -> list[str]:
    """Код(ы) для регистрации кандидата в pool_by_code (season_squad и
    round_squad services.py) — см. докстринг SLOT_PROCESSING_ORDER выше.

    :return: список из ОДНОГО кода — либо комбинированного "AMPLUA:ZONE",
      если сторона известна, либо голого "AMPLUA" для старых записей без
      field_position. Пустой список, если амплуа вообще не распознано."""
    amplua_code = clean_position_code(amplua)
    if not amplua_code:
        return []
    zone = _FIELD_POSITION_ZONE.get(clean_position_code(field_position), "")
    if zone:
        return [f"{amplua_code}:{zone}"]
    return [amplua_code]

