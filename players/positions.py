# Мини-схема поля на странице игрока (2026-09-09, вопрос пользователя после
# фикса DETAILED_POSITION_ID_MAP в parsers/sportmonks/importers.py: "плюс
# могли бы в профайле показывать мини схему поля и там все позиции игрока
# на которых он играет"). Источник данных — MatchLineupPlayer.position по
# ВСЕМ сыгранным матчам игрока (см. players/views.py::PlayerDetailView),
# то есть чем точнее приходят коды из Sportmonks (детальные, не грубые
# GK/D/M/F), тем осмысленнее эта карта — прямое следствие того же фикса.
#
# Вертикальная схема, атака СВЕРХУ (y=0), свои ворота СНИЗУ (y=100), x — от
# 0 (левый край) до 100 (правый), от лица зрителя со стороны трибуны за
# воротами защищающейся команды. Это ОБОБЩЁННАЯ карта "где играл за
# карьеру", а не точные координаты конкретного матча (для точных координат
# нужен был бы formation_field по каждому матчу отдельно — избыточно для
# задачи "показать все позиции игрока").
#
# "CB" — общая точка для обоих центральных защитников: сырые данные не
# различают CB1/CB2 без отдельного field_position, различать их тут не
# нужно. "D"/"M"/"F"/"DF"/"MF"/"FW"/"W" — грубые fallback-коды (старые
# записи KFF или матчи, куда detailedposition ещё не долетел).
#
# 2026-09-09 (жалоба со скриншотом: "у игроков есть позиции, которые
# накладываются друг на друга") — расстояние между соседними ЛИНИЯМИ
# (GK/защита/опорник/центр/атака) увеличено и выровнено (было неравномерно:
# DM-CM всего 10 пунктов, тогда как AM-CF — 24), чтобы у игрока с
# несколькими центральными позициями (DM+CM+AM — обычное дело) кружки не
# садились впритык друг к другу. Само по себе совпадение с декоративной
# разметкой поля (центральный круг и т.д.) больше не проблема — маркер
# теперь рисуется поверх непрозрачной "подложки" того же цвета, что фон
# схемы (см. templates/players/_position_map.html), которая перекрывает
# любую линию поля под собой, а не только эта конкретная точка.
