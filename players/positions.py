# Группа позиции — используется ТОЛЬКО для цвета бейджа на мини-схеме
# (templates/players/_position_map.html): вратарь/защита/полузащита/атака,
# тот же принцип раскраски, что в типичных scouting-отчётах (FM/Wyscout-
# style: защитники синим, полузащитники зелёным, нападающие красным).
_POSITION_GROUP: dict[str, str] = {
    "GK": "gk",
    "LB": "def", "LWB": "def", "CB": "def", "DF": "def", "D": "def",
    "RB": "def", "RWB": "def",
    "DM": "mid", "CM": "mid", "MF": "mid", "M": "mid",
    "LM": "mid", "RM": "mid", "AM": "mid",
    "LW": "fwd", "RW": "fwd", "W": "fwd",
    "CF": "fwd", "ST": "fwd", "F": "fwd", "FW": "fwd",
}


def player_position_breakdown(counts: dict[str, int]) -> list[dict]:
    """Готовит точки для мини-схемы поля (templates/players/_position_map.html)
    из {код позиции: сколько матчей игрок так сыграл}. Коды без известных
    координат/подписи молча пропускаются — лучше не нарисовать точку, чем
    нарисовать её в произвольном месте поля. Отсортировано по убыванию
    частоты — templates использует первую строку как "основная позиция"."""
    rows = []
    for raw_code, count in counts.items():
        if not count:
            continue
        code = clean_position_code(raw_code)
        coords = PITCH_COORDS.get(code)
        label = position_label(code)
        if not coords or not label:
            continue
        x, y = coords
        rows.append({
            "code": code, "label": label, "count": count, "x": x, "y": y,
            "group": _POSITION_GROUP.get(code, "mid"),
        })
    rows.sort(key=lambda r: r["count"], reverse=True)
    return rows


