"""
Нормализация позиций игроков. Исторический источник сырых данных — KFF
API, поле `amplua`/`position` в ответе на состав (parsers/kff/importers.py) —
приходил произвольным регистром и без единого словаря значений (видели на
практике: "DM", "M", "F", "GK", "Gk" вперемешку для одного и того же
амплуа), отсюда и clean_position_code() ниже. С 2026-09-08 (docs/
sportmonks-migration-plan.md) АКТИВНЫЙ источник — Sportmonks: там позиция
приходит уже контролируемым числовым `position_id` (24/25/26/27), который
parsers/sportmonks/importers.py::POSITION_ID_MAP сразу мапит на канонические
"GK"/"D"/"M"/"F" — то есть пишет уже нормализованный код напрямую, минуя
clean_position_code() (он ей просто не нужен, там нет разнобоя регистра).
Оба пути сходятся в одни и те же ключи POSITION_LABELS ниже — "GK"/"D"/"M"/
"F" были уже покрыты для KFF, отдельного расширения словаря не потребовалось.

2026-09-09 (вопрос пользователя про точность позиций после проблем с
парсингом КФФ): добавлен ВТОРОЙ, более точный источник —
parsers/sportmonks/importers.py::DETAILED_POSITION_ID_MAP, из nested
include "lineups.detailedposition". Он пишет уже гранулярные коды (CB/RB/
LB/DM/CM/AM/LW/RW/LM/RM/CF) напрямую в те же ключи POSITION_LABELS —
именно ради этого словарь ниже уже давно включал эти коды (задел на
будущее). Приоритет в import_lineups(): detailedposition, если пришёл,
иначе fallback на грубый position_id.
Модель Player.position и MatchLineupPlayer.position — свободный CharField
БЕЗ choices намеренно: неизвестный код лучше сохранить как есть (на случай
будущего маппинга), чем потерять данные или уронить импорт.

Разделение по двум функциям — намеренное:
- clean_position_code(): вызывается при ЗАПИСИ (импорт из KFF, миграция
  бэкафилла) — только normalizует регистр/пробелы, НЕ теряет данные, даже
  если код не входит в POSITION_LABELS (парсер может завтра прислать новый
  валидный код, которого ещё нет в словаре — не должны его портить).
- position_label(): вызывается при ОТОБРАЖЕНИИ (шаблоны) — возвращает
  None для нераспознанных кодов, чтобы шаблон показал "—", а не
  сырую аббревиатуру, вводящую пользователя в заблуждение.
"""
