    # на живой БД показал 'D' как САМУЮ БОЛЬШУЮ группу — 2153 строки, больше
    # чем 'M'/'DM'/'F'/'GK' — то есть KFF ни разу не прислал 'DF', только
    # укороченное 'D'. Без этого алиаса ни один защитник не попадал ни в
    # POSITION_LABELS (отображение "—" вместо подписи), ни в
    # SLOT_PROCESSING_ORDER пулы (пустые CB1/CB2/RB/LB слоты и в "Сборной
    # DOPX сезона", и в "DOPX Лучшие тура" — баг, из-за которого защитники
