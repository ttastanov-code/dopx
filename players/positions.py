# ИСПРАВЛЕНО (2026-09-22, жалоба пользователя со скриншотом: сборная тура
# поставила игрока на правый фланг — потому что squad-логика (см.
# resolve_lineup_codes/SLOT_PROCESSING_ORDER ниже) смотрит НЕ ТОЛЬКО на
# голое амплуа, а на комбинацию амплуа+field_position (сторона матча) — а
# мини-схема на его же профиле в это же время показывала ТОЛЬКО голые
# центральные коды ("M"/"F"), без единого намёка на фланг. КОРНЕВАЯ
# ПРИЧИНА: player_position_breakdown() (и вызывающий её players/views.py)
# считал счётчик исключительно по MatchLineupPlayer.position, вообще не
# заглядывая в field_position — та же самая информация, которую squad-
# логика уже использует для выбора слота, здесь игнорировалась целиком.
#
# Амплуа, которые уже сами по себе однозначно сторонние в POSITION_LABELS/
# PITCH_COORDS (RB/LB/RM/LM/RW/LW и т.п.), трогать не нужно — там сторона
# уже видна. Проблема — с АМБИВАЛЕНТНЫМИ кодами без стороны в самом
# амплуа (голый "D"/"M"/"AM"/"F" и синонимы) — именно для них, если у
# конкретного появления известна зона (L/R) из field_position, подменяем
# код на боковой эквивалент той же строки атаки/обороны. "DM" сюда
# намеренно не включён — DM:L/DM:R в SLOT_PROCESSING_ORDER ниже лишь
# техническое разделение CM1/CM2 в сборной, а не реальная "левая/правая
# опорная" позиция на поле, подменять её на LM/RM было бы введением в
# заблуждение на странице конкретного игрока.
_ZONE_SIDE_EQUIVALENT: dict[str, dict[str, str]] = {
    "D": {"L": "LB", "R": "RB"}, "DF": {"L": "LB", "R": "RB"}, "CB": {"L": "LB", "R": "RB"},
    "M": {"L": "LM", "R": "RM"}, "CM": {"L": "LM", "R": "RM"}, "MF": {"L": "LM", "R": "RM"},
    "AM": {"L": "LW", "R": "RW"},
    "F": {"L": "LW", "R": "RW"}, "FW": {"L": "LW", "R": "RW"},
    "CF": {"L": "LW", "R": "RW"}, "ST": {"L": "LW", "R": "RW"},
}


def player_position_display_code(amplua: str | None, field_position: str | None) -> str:
    """Код для мини-схемы профиля (см. докстринг выше про _ZONE_SIDE_
    EQUIVALENT) — учитывает зону (L/C/R) из field_position так же, как
    resolve_lineup_codes() ниже учитывает её для сборной тура/сезона.
    Использует ТОТ ЖЕ _FIELD_POSITION_ZONE (определён ниже в этом файле,
    заранее объявлять до вызова не обязательно — Python резолвит имя
    функции в момент вызова, а не в момент определения), чтобы "LC"/"RC"
    (край защитной тройки, не полноценный фланг) схлопывались в "C" точно
    так же, как и в squad-логике — не подписываем ЦЗ из тройки "левым
    защитником" только из-за небольшого смещения.

    Пустая строка, если амплуа вообще не распознано."""
    code = clean_position_code(amplua)
    if not code:
        return ""
    zone = _FIELD_POSITION_ZONE.get(clean_position_code(field_position), "")
    if zone in ("L", "R"):
        side_map = _ZONE_SIDE_EQUIVALENT.get(code)
        if side_map and zone in side_map:
            return side_map[zone]
    return code


def player_position_breakdown(counts: dict[str, int]) -> list[dict]:
    """Готовит точки для мини-схемы поля (templates/players/_position_map.html)
    из {код позиции: сколько матчей игрок так сыграл} — код должен уже быть
    посчитан через player_position_display_code() выше (учитывающий сторону),
    а не голым MatchLineupPlayer.position (см. players/views.py). Коды без
    известных координат/подписи молча пропускаются — лучше не нарисовать
    точку, чем нарисовать её в произвольном месте поля. Отсортировано по
    убыванию частоты — templates использует первую строку как "основная
    позиция"."""
    rows = []
    for raw_code, count in counts.items():
        if not count:
            continue
        code = clean_position_code(raw_code)
        coords = PITCH_COORDS.get(code)
        label = position_label(code)
        if not coords or not label:
            continue
        x, y = coords
        rows.append({
            "code": code, "label": label, "count": count, "x": x, "y": y,
            "group": _POSITION_GROUP.get(code, "mid"),
        })
    rows.sort(key=lambda r: r["count"], reverse=True)
    return rows


