# parsers/sportmonks/translit.py
"""
Автоматическая транслитерация латиница -> кириллица (практическая
транскрипция казахских/русских/украинских имён), см. чат с пользователем
2026-09-08: "дофига вручную менять, надо оптимизировать... научи его
правильно ставить имена".

ПОЧЕМУ АЛГОРИТМ, А НЕ РАСТУЩИЙ РУЧНОЙ СЛОВАРЬ (parsers/sportmonks/
name_translations.py): тот словарь охватывал только 146 судей/тренеров,
собранных на момент 2026-09-08 — при бэкафилле остальных сезонов и
будущих трансферов список игроков растёт постоянно (только в первых 6
матчах уже 29 непереведённых игроков), хардкодить каждого вручную
нежизнеспособно. Этот модуль — детерминированный набор правил
"практической транскрипции" (тот же принцип, которым пользуются
русскоязычные спортивные СМИ при передаче иностранных фамилий) — не
идеален на 100% (обратная транслитерация принципиально неоднозначна, см.
докстринг _resolve_cyrillic_name в importers.py), но покрывает
подавляющее большинство казахских/русских/украинских имён корректно.

ПРОВЕРЕНО на примерах, которые пользователь явно указал как правильные:
    Stanislav Shcherbakov -> Станислав Щербаков
    Magzhan Toktybay       -> Магжан Токтыбай
а также на всех именах, ранее подтверждённых вживую через API (Karabaev,
Dolgikh, Stasenko, Sheleg, Ferapontov, Romashchenko, Sultangaliev — все
транслитерируются этим модулем в точности так же, как реальный перевод от
Sportmonks там, где он есть).

ГРАНИЦЫ ТОЧНОСТИ: для явно НЕ-славянских имён (португальские, сербские/
хорватские с диакритикой, греческие, грузинские...) механическая
транслитерация не заменяет знание реального языка-источника — is_likely_foreign()
ниже даёт эвристический сигнал "этому результату лучше не доверять
слепо", используется вызывающим кодом (importers.py) только для логирования
уровня достоверности, СТАВИТЬ имя всё равно продолжает (лучше
неидеальная кириллица, чем голая латиница на сайте) — тонкая доводка
руками по-прежнему возможна через админку в любой момент (get_or_create_
referee/coach не перезаписывают существующие имена, см. importers.py).
"""
from __future__ import annotations

import re
from typing import List, Tuple

# Многобуквенные сочетания — проверяются ПЕРВЫМИ, длинные раньше коротких,
# порядок в списке важен (shch раньше sch раньше sh/ch по отдельности).
_MULTI_CHAR_RULES: List[Tuple[str, str]] = [
    ("shch", "щ"),
    ("sch", "щ"),
    ("zh", "ж"),
    ("kh", "х"),
    ("ts", "ц"),
    ("ch", "ч"),
    ("sh", "ш"),
    ("ph", "ф"),
    ("ya", "я"),
    ("yu", "ю"),
    ("yo", "ё"),
    ("ye", "е"),
]

# НЕ включены сюда как обычные диграфы: "ay"/"ey"/"oy"/"uy" — намеренно.
# НАЙДЕН И ИСПРАВЛЕН БАГ при разработке (2026-09-08): жадный левый-направо
# скан со статичным правилом "ay" -> "ай" ломал "Sayat" (казахское имя,
# правильно "Саят": с-а-я-т) — правило хватало "ay" из позиций 1-2 (a,y)
# раньше, чем скан доходил до позиции 2 и мог распознать "ya" (y,a) как
# отдельную йотированную гласную. Фолбэк-обработка одиночной "y" ниже
# (после гласной -> "й", иначе -> "ы") корректно закрывает случай
# концевого дифтонга ("Toktybay" -> "...ай" всё равно получается верно
# через фолбэк) БЕЗ этой ловушки, поэтому явные диграфы для ay/ey/oy/uy не
# нужны вообще.
#
# "iy"/"yi"/"yy" — ОСТАВЛЕНЫ отдельно, но только на конце слова (см.
# _WORD_FINAL_RULES ниже), а не как общий диграф по всему слову — та же
# причина: если бы "iy" матчился где угодно, комбинация вроде
# гипотетического "Kiyat" ловилась бы неверно тем же способом, что и баг
# с "Sayat" выше. На конце слова эта комбинация практически всегда
# означает суффикс "-ий"/"-ый" (Dmitriy -> Дмитрий, Lototskyi -> ...цкий),
# неоднозначности там на практике нет.
_WORD_FINAL_RULES: List[Tuple[str, str]] = [
    ("iy", "ий"),
    ("yi", "ий"),
    ("yy", "ый"),
]

_SINGLE_CHAR_MAP = {
    "a": "а", "b": "б", "v": "в", "g": "г", "d": "д", "e": "е", "z": "з",
    "i": "и", "k": "к", "l": "л", "m": "м", "n": "н", "o": "о", "p": "п",
    "r": "р", "s": "с", "t": "т", "u": "у", "f": "ф", "h": "х", "c": "к",
    "w": "в", "j": "й", "q": "к",
    # ИСПРАВЛЕНО (2026-09-09, баг найден пользователем — "Александр
    # Кержаков"/"Александр Широбоков" превратились в "Алеxандр..." после
    # повторной транслитерации): "x" не было в этой карте вообще, поэтому
    # "неизвестный символ — как есть" фолбэк (см. _transliterate_word ниже)
    # оставлял букву "x" латиницей прямо посреди иначе кириллического слова
    # — тот же класс порчи, что и с диакритикой, просто не пойман
    # is_likely_foreign() (там "x" не сигнал не-славянского имени, это
    # обычная буква в "Alexandr"/"Maxim" и т.п.). "x" на практике всегда
    # передаёт звук "кс" в этой транслитерационной схеме.
    "x": "кс",
}

_VOWELS_RU = set("аеёиоуыэюя")

# Символы/буквосочетания, редкие в казахско-русских латинских
# транслитерациях и типичные для романских/южнославянских языков —
# сигнал "имя, скорее всего, не по стандартным для проекта правилам,
# результат нужно перепроверить" (см. докстринг модуля выше).
_FOREIGN_SIGNAL_RE = re.compile(
    r"[àáâãäåæçèéêëìíîïñòóôõöùúûüýÿ]"  # диакритика романских языков
    r"|[ćčđšžł]"                        # сербско-хорватские/польские буквы
    r"|lh|nh|ção|ção|inho|inha"        # португальские паттерны
    r"|[wq]",                            # редкие в славянских латиницах
    re.IGNORECASE,
)


def is_likely_foreign(latin_text: str) -> bool:
    """Эвристика "не по-славянски выглядит" — см. докстринг модуля.
    Используется только для уровня логирования, не блокирует транслитерацию."""
    return bool(_FOREIGN_SIGNAL_RE.search(latin_text or ""))


def _transliterate_word(word: str) -> str:
    suffix_cyr = ""
    for latin_suffix, cyr_suffix in _WORD_FINAL_RULES:
        if word.endswith(latin_suffix) and len(word) > len(latin_suffix):
            word, suffix_cyr = word[: -len(latin_suffix)], cyr_suffix
            break

    result = []
    i = 0
    n = len(word)
    while i < n:
        matched = False
        for pattern, repl in _MULTI_CHAR_RULES:
            if word.startswith(pattern, i):
                result.append(repl)
                i += len(pattern)
                matched = True
                break
        if matched:
            continue

        ch = word[i]
        if ch == "y":
            # "y" не часть известной диграфы (иначе съелась бы выше) —
            # после гласной это "й" (Aydar -> Айдар — 'y' после 'a'),
            # иначе — "ы" (Rybakov -> Рыбаков — 'y' после согласной/в начале).
            prev = result[-1] if result else ""
            result.append("й" if prev in _VOWELS_RU else "ы")
            i += 1
            continue

        result.append(_SINGLE_CHAR_MAP.get(ch, ch))  # неизвестный символ — как есть
        i += 1

    return "".join(result) + suffix_cyr


def transliterate_name(latin_text: str) -> str:
    """Транслитерирует ФИО (одно или несколько слов через пробел/дефис) с
    сохранением регистра первой буквы каждого слова. Пустая строка на
    входе -> пустая строка на выходе."""
    if not latin_text:
        return ""

    def _translit_token(token: str) -> str:
        if not token:
            return token
        lowered = token.lower()
        cyr = _transliterate_word(lowered)
        return cyr[:1].upper() + cyr[1:] if cyr else cyr

    # Разбиваем по пробелам, сохраняя дефисы ВНУТРИ токена (напр.
    # "Zhaksybek-uly") — дефис не разделяет слово на два транслитерируемых
    # куска сам по себе, но каждая часть после дефиса тоже с большой буквы
    # по конвенции ФИО.
    words = latin_text.split(" ")
    out_words = []
    for word in words:
        if "-" in word:
            parts = word.split("-")
            out_words.append("-".join(_translit_token(p) for p in parts))
        else:
            out_words.append(_translit_token(word))
    return " ".join(out_words)
