// БАГ, КОТОРЫЙ ТУТ БЫЛ (жалоба пользователя, 2026-08-29): кнопка браузера
// "назад" корректно возвращает на страницу списка (/matches/, /players/,
// ...) ровно туда, где пользователь был — на нужной странице пагинации,
// с теми же фильтрами, на той же позиции скролла (см. scroll-restore.js).
// А вот кнопки "Назад к матчам"/"Назад к игрокам"/"Назад к профилю" и т.п.
// прямо на страницах — НЕТ: это обычные <a href="{% url '...:list' %}">
// на ФИКСИРОВАННЫЙ URL списка без ?page=/?status=/... — клик всегда вёл
// на первую страницу списка без фильтров, даже если пользователь пришёл
// со страницы 9 с применённым фильтром по туру.
//
// Раньше эти ссылки нужно было бы чинить по одной, прокидывая query-string
// исходной страницы через каждую detail-вьюху (matches/teams/players/
// coaches/referees/leagues + users:profile/leaderboard) — вместо этого
// переиспользуем то, что уже гарантированно работает правильно: реальную
// историю браузера (history.back()), а не жёстко прописанный URL. Ссылка
// остаётся обычным <a href="..."> (это фолбэк — если пользователь открыл
// страницу матча напрямую по ссылке, извне сайта, идти в history.back()
// некуда и не нужно), и на неё просто вешается data-back-link — сайтвайд-
// делегирование клика ниже решает, использовать ли history.back() вместо
// перехода по href.
(function () {
  document.addEventListener('click', function (event) {
    // Игнорируем клики с модификаторами (Ctrl/Cmd/Shift/Alt) и не левой
    // кнопкой мыши — пользователь явно хочет открыть в новой вкладке/окне,
    // history.back() в текущей вкладке этому бы помешал.
    if (event.defaultPrevented || event.button !== 0 ||
        event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) {
      return;
    }

    var link = event.target.closest('[data-back-link]');
    if (!link) return;

    // history.back() имеет смысл, только если пользователь действительно
    // ПРИШЁЛ на эту страницу с другой страницы того же сайта (тогда в
    // истории браузера реально есть куда возвращаться с правильным
    // состоянием). Если document.referrer пуст или ведёт на другой домен
    // (прямая ссылка, переход из поиска/соцсети, открытие в новой вкладке)
    // — history.back() увёл бы вообще за пределы сайта или никуда, поэтому
    // в этих случаях используем обычный href-переход на список (то, что
    // ссылка и так уже делает по умолчанию).
    var sameOriginReferrer = false;
    try {
      sameOriginReferrer = !!document.referrer && new URL(document.referrer).origin === location.origin;
    } catch (e) {
      sameOriginReferrer = false;
    }

    if (sameOriginReferrer && window.history.length > 1) {
      event.preventDefault();
      window.history.back();
    }
    // иначе — ничего не делаем, клик доходит до обычной навигации по href
  });
})();
